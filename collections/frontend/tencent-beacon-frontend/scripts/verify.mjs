import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { compareForm } from './form-fidelity.mjs';
import { compareChat } from './chat-typography.mjs';

/** Runs through ego-browser nodejs; only operates on a loopback preview. */
export async function main({ taskSpaceId, pageLabel = 'p1', url = 'http://127.0.0.1:5192', output = '/tmp/tencent-beacon-verify' } = {}) {
  const address = new URL(url);
  if (!['http:', 'https:'].includes(address.protocol) || !['localhost', '127.0.0.1', '[::1]'].includes(address.hostname)) throw new Error('Verification requires a local preview URL.');
  const task = await taskSpace(taskSpaceId ?? `Beacon local verification ${Date.now()}`);
  console.log({ spaceId: task.spaceId, page: pageLabel });
  const page = task.page(pageLabel);
  const directory = resolve(output);
  await mkdir(directory, { recursive: true });
  const checks = [];
  const check = (name, success, details) => { checks.push({ name, pass: !!success, ...(details ? { details } : {}) }); if (!success) throw new Error(`Verification failed: ${name}`); };
  const settle = () => page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  const image = async (name, selector) => {
    await settle();
    await page.evaluate(() => Promise.all(document.getAnimations().filter(animation => Number.isFinite(animation.effect?.getComputedTiming().endTime)).map(animation => animation.finished.catch(() => {}))));
    await settle();
    const clip = selector ? await page.evaluate(selector => { const r = document.querySelector(selector).getBoundingClientRect(); return { x: r.x, y: r.y, width: r.width, height: r.height, scale: 1 }; }, selector) : undefined;
    if (await page.evaluate(() => innerWidth > 760)) {
      await page.screenshot({ path: resolve(directory, name), ...(clip ? { clip: { x: clip.x, y: clip.y, width: clip.width, height: clip.height } } : {}) });
    } else {
      const shot = await page.cdp('Page.captureScreenshot', { format: 'png', captureBeyondViewport: false });
      await writeFile(resolve(directory, name), Buffer.from(shot.data, 'base64'));
    }
  };
  try {
    await page.goto(address.href);
    await page.waitForSelector('[data-ui="workspace"]');
    await page.evaluate(() => document.fonts.ready.then(() => true));
    await compareChat(page, resolve(directory, 'chat-typography.json'));
    check('chat typography matches source', true);
    await page.waitForFunction(() => [...document.images].every(image => image.complete && image.naturalWidth > 0));
    await page.cdp('Emulation.setDeviceMetricsOverride', { width: 1920, height: 975, deviceScaleFactor: 1, mobile: false });
    await settle();
    check('initial empty state', await page.evaluate(() => document.querySelector('.beacon-list-count').textContent.includes('共 0 个数据集') && document.querySelector('[aria-label="发送消息"]').disabled));
    const layout = await page.evaluate(() => {
      const rect = selector => { const r = document.querySelector(selector).getBoundingClientRect(); return { x: r.x, y: r.y, width: r.width, height: r.height }; };
      return { chat: rect('[data-ui="chat"]'), workspace: rect('[data-ui="workspace"]'), composer: rect('[data-ui="composer"]') };
    });
    check('desktop reference geometry', Math.abs(layout.chat.x - 180) <= 1 && Math.abs(layout.workspace.x - 846) <= 3 && Math.abs(layout.composer.y - 796) <= 3, layout);
    await image('desktop.png');
    await page.click('[aria-label="按数据来源筛选：全部"]', { label: '验证数据来源菜单' });
    await page.waitForSelector('[role="menu"]');
    check('source menu options', await page.evaluate(() => document.querySelectorAll('[role="menuitem"]').length === 10));
    await image('source-menu.png');
    await page.keyboard.press('Escape');
    await page.waitForSelector('[role="menu"]', { state: 'hidden' });
    check('menu escape restores focus', await page.evaluate(() => document.activeElement?.getAttribute('aria-label') === '按数据来源筛选：全部'));
    await page.click('loc=role:button[name="新建数据集"]', { label: '验证新建数据集' });
    await page.waitForSelector('[role="dialog"]');
    await page.fill('input[placeholder="数据集名称"]', '销售数据演示');
    await page.click('[aria-label="选择数据来源"]', { label: '选择示例数据来源' });
    await page.waitForSelector('[role="menu"]');
    await page.click('loc=role:menuitem[name="MySQL"]', { label: '选择 MySQL 数据源' });
    await page.click('button[type="submit"]', { label: '创建本地示例数据集' });
    await page.waitForSelector('table');
    check('dataset creates local table', await page.evaluate(() => document.querySelectorAll('tbody tr').length === 3 && document.querySelector('.beacon-list-count').textContent.includes('共 1 个数据集')));
    await image('dataset.png');
    await page.fill('[aria-label="搜索数据集"]', '不存在的数据集');
    check('dataset query filters list', await page.evaluate(() => document.querySelector('.beacon-list-empty')?.textContent === '无匹配数据集'));
    await page.fill('[aria-label="搜索数据集"]', '');
    await page.click('[aria-label="按数据来源筛选：全部"]', { label: '验证来源组合筛选' });
    await page.waitForSelector('[role="menu"]');
    await page.click('loc=role:menuitem[name="腾讯文档"]', { label: '筛选腾讯文档数据集' });
    check('source filters independently', await page.evaluate(() => document.querySelector('.beacon-list-empty')?.textContent === '无匹配数据集'));
    await page.click('[aria-label="按数据来源筛选：腾讯文档"]', { label: '清除数据来源筛选' });
    await page.waitForSelector('[role="menu"]');
    await page.click('loc=role:menuitem[name="全部"]', { label: '恢复全部数据集' });
    await page.click('loc=role:tab[name="数据连接"]', { label: '验证数据连接标签页' });
    await page.waitForSelector('[aria-label="搜索数据连接"]');
    check('connection empty state', await page.evaluate(() => document.querySelector('.beacon-list-empty')?.textContent === '暂无数据连接'));
    await page.click('.beacon-new-connection-link', { label: '打开 MySQL 连接表单' });
    await page.click('[aria-label="选择 MySQL：连接 MySQL 数据库，复用于多个数据集"]', { label: '选择 MySQL 连接类型' });
    await page.waitForSelector('[data-ui="connection-form"]');
    check('connection form reference layout', await page.evaluate(() => {
      const card = document.querySelector('.beacon-connection-card').getBoundingClientRect();
      const workspace = document.querySelector('[data-ui="workspace"]').getBoundingClientRect();
      return Math.abs(card.width - 576) <= 1 && Math.abs(card.x - workspace.x - 306) <= 2 && document.querySelector('input[name="port"]').value === '3306' && document.querySelector('input[value="HTTP"]').checked;
    }));
    const fidelity = await compareForm(page, { reportPath: resolve(directory, 'form-fidelity.json') });
    check('form matches captured source presentation', fidelity.differences.length === 0);
    await image('connection-form.png', '[data-ui="workspace"]');
    await page.click('.beacon-connection-footer button[type="submit"]', { label: '验证空表单必填校验' });
    check('empty connection cannot submit', await page.evaluate(() => document.querySelector('.beacon-connection-error')?.textContent === '请填写数据连接名称' && document.querySelector('.beacon-list-count').textContent.includes('共 0 个数据连接')));
    await page.fill('input[name="host"]', 'mysql.example.test');
    await page.click('.beacon-connection-test', { label: '验证缺失参数提示' });
    check('missing connection fields show source message', await page.evaluate(() => document.querySelector('.beacon-connection-error')?.textContent === '请填写完整的连接信息'));
    await page.fill('input[name="database"]', 'analytics');
    await page.fill('input[name="username"]', 'preview_user');
    await page.fill('input[name="password"]', 'preview-only-dummy');
    await page.fill('input[name="name"]', '运营数据库');
    await page.fill('input[name="port"]', '3306');
    await page.click('input[name="protocol"][value="TCP"]', { label: '切换 TCP 连接协议' });
    await page.click('[aria-label="展开管理员选项"]', { label: '打开管理员候选列表' });
    await page.waitForSelector('[role="listbox"]');
    await page.fill('#beacon-administrators', 'user001');
    await page.press('#beacon-administrators', 'ArrowDown');
    await page.press('#beacon-administrators', 'Enter');
    await page.waitForSelector('.beacon-admin-chip');
    check('administrators support keyboard selection', await page.evaluate(() => document.querySelector('.beacon-admin-chip').textContent.includes('user001')));
    await page.fill('#beacon-administrators', '');
    await page.keyboard.paste('user004,user005');
    check('administrators accept pasted ids', await page.evaluate(() => document.querySelectorAll('.beacon-admin-chip').length === 3));
    await page.keyboard.press('Escape');
    await page.click('.beacon-connection-test', { label: '验证本地连接测试反馈' });
    check('connection test reports preview boundary', await page.evaluate(() => document.querySelector('.beacon-connection-status')?.textContent.includes('未连接数据库') && document.querySelector('input[value="TCP"]').checked && document.querySelector('input[name="password"]').type === 'password'));
    await page.fill('input[name="host"]', 'mysql-updated.example.test');
    check('editing clears stale test status', await page.evaluate(() => !document.querySelector('.beacon-connection-status')));
    await page.click('.beacon-connection-footer button[type="submit"]', { label: '提交本地示例连接' });
    await page.waitForSelector('[data-ui="connection-detail"]');
    check('connection saves without password', await page.evaluate(() => document.querySelector('.beacon-list-count').textContent.includes('共 1 个数据连接') && document.querySelector('[data-ui="connection-detail"]').textContent.includes('运营数据库') && !document.body.textContent.includes('preview-only-dummy') && !document.querySelector('input[name="password"]')));
    await page.click('.beacon-new-connection-link', { label: '检查新建表单重置' });
    await page.click('[aria-label="选择 MySQL：连接 MySQL 数据库，复用于多个数据集"]', { label: '重新选择 MySQL' });
    await page.waitForSelector('[data-ui="connection-form"]');
    check('new connection resets draft', await page.evaluate(() => document.querySelector('input[name="host"]').value === '' && document.querySelector('input[name="port"]').value === '3306' && !document.querySelector('.beacon-admin-chip')));
    await page.fill('input[name="host"]', 'cancelled.example.test');
    await page.click('.beacon-connection-footer button[type="button"]', { label: '取消未提交连接' });
    check('cancel preserves existing connections', await page.evaluate(() => !document.querySelector('[data-ui="connection-form"]') && document.querySelector('.beacon-list-count').textContent.includes('共 1 个数据连接')));
    await page.press('loc=role:tab[name="数据连接"]', 'Home');
    await page.waitForSelector('[aria-label="搜索数据集"]');
    check('tab keyboard navigation', await page.evaluate(() => document.activeElement?.textContent === '数据集'));
    await page.click('[aria-label="收起侧栏"]', { label: '验证侧栏收起' });
    check('sidebar collapses', await page.evaluate(() => document.querySelector('[data-ui="sidebar"]').getBoundingClientRect().width === 44));
    await page.click('[aria-label="展开侧栏"]', { label: '恢复完整侧栏' });
    await page.click('[aria-label="铺满页面"]', { label: '验证工作区铺满' });
    await settle();
    check('workspace expands', await page.evaluate(() => document.getElementById('beacon-chat').getBoundingClientRect().width < 2));
    await page.click('[aria-label="退出铺满"]', { label: '恢复三栏布局' });
    await page.click('loc=role:button[name="分析收入变化"]', { label: '验证建议填入输入区' });
    check('suggestion fills composer', await page.evaluate(() => document.querySelector('textarea').value === '分析收入变化'));
    await page.press('textarea', 'Enter');
    await page.waitForSelector('.beacon-user-message');
    check('message stays local', await page.evaluate(() => document.querySelector('.beacon-user-message').textContent === '分析收入变化' && document.querySelector('textarea').value === '' && document.querySelector('[aria-label="发送消息"]').disabled));
    await page.click('[aria-label="新对话"]', { label: '恢复新对话空态' });
    await page.waitForSelector('.beacon-welcome');
    await page.cdp('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: false });
    await settle();
    check('mobile chat fits viewport', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth && getComputedStyle(document.getElementById('beacon-data')).display === 'none'));
    await image('mobile-chat.png');
    await page.click('.beacon-mobile-tabs button:nth-child(2)', { label: '验证窄屏数据视图' });
    await settle();
    check('mobile workspace fits viewport', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth && document.querySelector('[data-ui="workspace"]').getBoundingClientRect().width <= innerWidth && getComputedStyle(document.getElementById('beacon-chat')).display === 'none'));
    await image('mobile-data.png');
    await page.click('loc=role:tab[name="数据连接"]', { label: '检查窄屏连接表单入口' });
    await page.click('[aria-label="选择 MySQL：连接 MySQL 数据库，复用于多个数据集"]', { label: '选择窄屏连接类型' });
    await page.waitForSelector('[data-ui="connection-form"]');
    await settle();
    check('mobile connection form and footer fit', await page.evaluate(() => {
      const card = document.querySelector('.beacon-connection-card');
      const footer = document.querySelector('.beacon-connection-footer').getBoundingClientRect();
      return document.documentElement.scrollWidth <= innerWidth && card.scrollWidth <= card.clientWidth && footer.bottom <= innerHeight && getComputedStyle(document.querySelector('.beacon-dataset-list')).display === 'none';
    }));
    await image('mobile-connection-form.png');
    await page.cdp('Emulation.setDeviceMetricsOverride', { width: 1920, height: 975, deviceScaleFactor: 1, mobile: false });
    await settle();
    const typography = await page.evaluate(() => {
      const sizes = [...new Set([...document.querySelectorAll('.beacon-app *')].filter(el => !el.closest('.beacon-connection-page, .beacon-chat') && el.children.length === 0 && el.textContent.trim() && el.getBoundingClientRect().width > 0).map(el => parseFloat(getComputedStyle(el).fontSize)))];
      const chevrons = [...document.querySelectorAll('.beacon-menu-trigger')].filter(el => el.textContent.trim()).every(el => el.querySelectorAll('.beacon-chevron').length === 1 && getComputedStyle(el.querySelector('.beacon-chevron')).display !== 'none');
      return { sizes, chevrons };
    });
    check('type scale and text-menu chevrons', typography.sizes.length <= 4 && typography.sizes.every(size => size >= 12) && typography.chevrons, typography);
    await page.goto(address.href);
    await page.waitForSelector('[data-ui="workspace"]');
    await writeFile(resolve(directory, 'report.json'), JSON.stringify({ url: address.href, checked: new Date().toISOString(), checks }, null, 2) + '\n');
    console.log({ passed: checks.length, output: directory });
    if (taskSpaceId === undefined) await task.finish({ keep: [] });
    return checks;
  } catch (error) {
    await writeFile(resolve(directory, 'report.json'), JSON.stringify({ checks, error: String(error), spaceId: task.spaceId, page: pageLabel }, null, 2) + '\n');
    throw error;
  }
}
